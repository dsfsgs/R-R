// scripts/build-fonts-vfs.js
//
// Scans src/assets/fonts/ for every .ttf, groups files by family,
// and generates two artifacts:
//
//   src/assets/fonts/fonts_vfs.js   — { "Filename.ttf": "<base64>" }
//   src/assets/fonts/fonts_map.js   — { Family: { normal, bold, ... } }
//
// Run once, then again whenever fonts change:
//   node scripts/build-fonts-vfs.js
//
// Family detection:
//   Splits the filename at the first '-' or '_'.
//   Everything before it is the family name.
//   Everything after it is parsed into a variant (normal/bold/italic).
//
//   Candara.ttf            → Candara / normal
//   Candara_Bold.ttf       → Candara / bold
//   Poppins-Regular.ttf    → Poppins / normal
//   Poppins-BoldItalic.ttf → Poppins / bolditalics

const fs = require("fs");
const path = require("path");

const FONTS_DIR = path.resolve(__dirname, "../src/assets/fonts");
const VFS_OUTPUT = path.join(FONTS_DIR, "fonts_vfs.js");
const MAP_OUTPUT = path.join(FONTS_DIR, "fonts_map.js");

/**
 * Parse a font filename into { family, variant }.
 * Handles both `Family_Variant.ttf` and `Family-Variant.ttf`,
 * and both `BoldItalic` and `Bold_Italic`.
 */
function parseFontFile(basename) {
  const name = basename.replace(/\.ttf$/i, "");

  // Find the first separator (either _ or -)
  const sepIndex = name.search(/[_-]/);

  let family;
  let rest;

  if (sepIndex === -1) {
    // No separator → family-only file, treat as normal weight
    family = name;
    rest = "";
  } else {
    family = name.slice(0, sepIndex);
    rest = name.slice(sepIndex + 1);
  }

  const lower = rest.toLowerCase();
  const isBold =
    lower.includes("bold") ||
    lower.includes("semibold") ||
    lower.includes("heavy") ||
    lower.includes("black");
  const isItalic = lower.includes("italic") || lower.includes("oblique");

  let variant;
  if (isBold && isItalic) variant = "bolditalics";
  else if (isBold) variant = "bold";
  else if (isItalic) variant = "italics";
  else variant = "normal";

  return { family, variant };
}

function main() {
  if (!fs.existsSync(FONTS_DIR)) {
    console.error(`Fonts directory not found: ${FONTS_DIR}`);
    process.exit(1);
  }

  const files = fs
    .readdirSync(FONTS_DIR)
    .filter((f) => /\.ttf$/i.test(f))
    .sort();

  if (files.length === 0) {
    console.error(`No .ttf files found in ${FONTS_DIR}`);
    process.exit(1);
  }

  console.log(`Found ${files.length} font file(s):\n`);

  const families = {};
  const vfs = {};

  for (const file of files) {
    const { family, variant } = parseFontFile(file);

    if (!families[family]) families[family] = {};
    if (families[family][variant]) {
      console.warn(
        `  ! Duplicate ${family}.${variant} — keeping "${families[family][variant]}", ignoring "${file}"`
      );
      continue;
    }
    families[family][variant] = file;

    const buffer = fs.readFileSync(path.join(FONTS_DIR, file));
    vfs[file] = buffer.toString("base64");

    console.log(
      `  + ${file.padEnd(30)} → ${family}.${variant.padEnd(12)} (${(
        buffer.length / 1024
      ).toFixed(1)} KB)`
    );
  }

  // Fill missing variants with the normal file so pdfmake still renders
  for (const family of Object.keys(families)) {
    const map = families[family];
    if (!map.normal) {
      console.error(
        `\nFamily "${family}" has no normal variant. Add a file like "${family}.ttf" or "${family}-Regular.ttf".`
      );
      process.exit(1);
    }
    map.bold = map.bold || map.normal;
    map.italics = map.italics || map.normal;
    map.bolditalics = map.bolditalics || map.bold || map.normal;
  }

  // Write VFS (huge base64 — no indentation)
  fs.writeFileSync(
    VFS_OUTPUT,
    "/* Auto-generated by scripts/build-fonts-vfs.js — do not edit manually */\n" +
      "/* Re-run the script when the font files change. */\n\n" +
      "export default " +
      JSON.stringify(vfs) +
      ";\n"
  );

  // Write map (small — indented for readability)
  fs.writeFileSync(
    MAP_OUTPUT,
    "/* Auto-generated by scripts/build-fonts-vfs.js — do not edit manually */\n" +
      "/* Re-run the script when the font files change. */\n\n" +
      "export default " +
      JSON.stringify(families, null, 2) +
      ";\n"
  );

  console.log(`\nWrote ${path.relative(process.cwd(), VFS_OUTPUT)}`);
  console.log(`Wrote ${path.relative(process.cwd(), MAP_OUTPUT)}`);
  console.log(`\nRegistered families: ${Object.keys(families).join(", ")}`);
}

main();
