/**
 * A label followed by a fill-in line whose underline sits ONLY under the
 * value area (not under the label).
 *
 * Two ways to render the value:
 *   1. `value` — a single string on the underline (default).
 *   2. `valueColumns` — an array of { width, text, alignment? } that
 *      renders the value as a multi-column table on the same underline.
 *      Use this when the field has sub-labels (e.g. name parts).
 *
 * Bottom spacing:
 *   - Plain fields (label + value only) get `PLAIN_GAP` pt of vertical
 *     space below.
 *   - Fields that carry a sub-label row or a subtitle get a smaller
 *     bottom margin because that extra content already pushes the next
 *     section down. The two values are tuned so the visual gap between
 *     every pair of sections ends up the same — neither cramped nor
 *     loose.
 *
 * Optional `options.valueFontSize` overrides the value text size
 * (defaults to 8). Useful for long fields such as Department/Office.
 */
const PLAIN_GAP = 12;
const EXTRA_GAP = 5;

function fieldLine(label, value, options = {}) {
  const hasExtra = Boolean(options.subLabels || options.subtitle);
  const valueFontSize = options.valueFontSize || 8;

  let valueWidths;
  let valueBody;

  if (options.valueColumns && options.valueColumns.length) {
    valueWidths = options.valueColumns.map((c) => c.width);
    valueBody = [
      options.valueColumns.map((c) => ({
        text: c.text || " ",
        fontSize: valueFontSize,
        color: "#19354a",
        alignment: c.alignment || "left",
      })),
    ];
  } else {
    valueWidths = ["*"];
    valueBody = [
      [
        {
          text: value || " ",
          fontSize: valueFontSize,
          color: "#19354a",
        },
      ],
    ];
  }

  const valueStack = [
    {
      table: {
        widths: valueWidths,
        body: valueBody,
      },
      layout: {
        hLineWidth: (i, node) => (i === node.table.body.length ? 0.8 : 0),
        hLineColor: () => "#5c6b78",
        vLineWidth: () => 0,
        paddingLeft: () => 0,
        paddingRight: () => 0,
        paddingTop: () => 0,
        paddingBottom: () => 1,
      },
    },
  ];

  if (options.subLabels) {
    valueStack.push({
      columns: options.subLabels.map((c) => ({
        width: c.width,
        text: c.text,
        alignment: "center",
        fontSize: 7,
        italics: true,
        color: "#6b7680",
        lineHeight: 1,
        margin: [0, 0, 0, 0],
      })),
    });
  }

  if (options.subtitle) {
    valueStack.push({
      text: options.subtitle,
      fontSize: 7,
      italics: true,
      color: "#6b7680",
      alignment: "center",
      lineHeight: 1,
      margin: [0, 0, 0, 0],
    });
  }

  const bottom = hasExtra ? EXTRA_GAP : PLAIN_GAP;

  return {
    columns: [
      {
        width: options.labelWidth || "auto",
        text: label,
        fontSize: 8,
        color: "#000000",
        margin: [0, 0, 4, 1],
      },
      {
        width: "*",
        stack: valueStack,
      },
    ],
    margin: options.margin || [0, 0, 0, bottom],
  };
}

function fieldRow(
  left,
  right,
  gap = 10,
  leftWidth = "60%",
  rightWidth = "40%"
) {
  return {
    columns: [
      { width: leftWidth, ...left },
      { width: gap, text: "" },
      { width: rightWidth, ...right },
    ],
  };
}

