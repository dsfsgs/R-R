function docsChecklist(record) {
  const docs = record.docs || {};
  const keys = Object.keys(docs);
  const matched = new Set();
  const items = [];

  // The signed form (once uploaded) IS the accomplished form — same
  // physical document, just signed by the employee. If a signed form
  // exists, tick the "Accomplished Form" line automatically.
  const hasSignedForm = Boolean(record?.signed_docs?.signed_form?.name);

  DOC_ITEMS.forEach((item) => {
    const hit = keys.find((k) => {
      if (matched.has(k)) return false;
      const nk = normalizeKey(k);
      return item.aliases.some((a) => nk.includes(a) || a.includes(nk));
    });
    if (hit) matched.add(hit);

    const isAccomplishedForm =
      item.label === "Accomplished Form" && hasSignedForm;

    items.push({
      label: item.label,
      checked: Boolean(hit) || isAccomplishedForm,
    });
  });

  keys.forEach((k) => {
    if (!matched.has(k)) items.push({ label: humanizeKey(k), checked: true });
  });

  const letters = "abcdefghijklmnopqrstuvwxyz";

  return {
    table: {
      widths: [34, 34, "*"],
      body: items.map((item, i) => [
        {
          text: `${letters[i] || "•"}.`,
          fontSize: 8,
          margin: [14, 1, 0, 1],
        },
        {
          text: `[  ${item.checked ? "X" : " "}  ]`,
          fontSize: 8,
          margin: [0, 1, 0, 1],
        },
        {
          text: item.label,
          fontSize: 8,
          margin: [6, 1, 0, 1],
        },
      ]),
    },
    layout: {
      hLineWidth: () => 0,
      vLineWidth: () => 0,
      paddingLeft: () => 0,
      paddingRight: () => 0,
      paddingTop: () => 0,
      paddingBottom: () => 3,
    },
    margin: [0, 0, 0, 12],
  };
}

