function formatFullName(record) {
  if (!record) return "";

  const surname = String(record.surname || "").trim();
  const firstname = String(record.firstname || "").trim();
  const middlename = String(record.middlename || "").trim();
  const suffix = String(record.suffix || "").trim();

  if (!surname && !firstname && !middlename && !suffix) {
    return "";
  }

  let name = surname;
  if (firstname) name += (name ? ", " : "") + firstname;
  if (middlename) {
    const mi = middlename.charAt(0).toUpperCase();
    name += (name ? " " : "") + mi + ".";
  }
  if (suffix) name += (name ? " " : "") + suffix;

  return name;
}

function normalizeKey(key) {
  return String(key)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function humanizeKey(key) {
  return key
    .split("_")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

function issuedDateParts(iso) {
  if (!iso) return null;
  const d = new Date(iso);
  if (isNaN(d)) return null;
  return {
    day: String(d.getDate()),
    month: d.toLocaleDateString("en-PH", { month: "long" }),
    year: String(d.getFullYear()),
  };
}

function formatDate(iso, fallback = "—") {
  if (!iso) return fallback;
  const d = new Date(iso);
  if (isNaN(d)) return iso;
  return d.toLocaleDateString("en-PH", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

function formatDateTime(iso) {
  if (!iso) return "—";
  const d = new Date(iso);
  if (isNaN(d)) return iso;
  return d.toLocaleString("en-PH", {
    year: "numeric",
    month: "long",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}
